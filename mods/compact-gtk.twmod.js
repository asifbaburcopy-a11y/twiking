'use strict';
/* User CSS: the one place where Linux really does match Windhawk's power over
 * other apps' appearance. Contributions go into ~/.config/gtk-N.0/gtk.css
 * inside a marker block, so other mods and hand-written CSS survive. */

module.exports = {
  meta: {
    id: 'compact-gtk',
    name: 'Compact GTK Layout',
    description: 'Slimmer header bars, tighter buttons and square corners via user CSS — reversible byte-for-byte.',
    version: '1.0.0',
    author: 'Twiking',
    category: 'Appearance',
    icon: 'css',
    license: 'MIT',
    tags: ['css', 'gtk', 'density', 'corners'],
    capabilities: ['files'],
    requires: { desktops: ['GNOME'] },
  },

  settings: [
    {
      key: 'density',
      name: 'Density',
      description: 'How much vertical space header bars and buttons take.',
      type: 'select',
      default: 'compact',
      options: [
        { value: 'normal', label: 'Normal' },
        { value: 'compact', label: 'Compact' },
        { value: 'dense', label: 'Dense' },
      ],
    },
    { key: 'squareCorners', name: 'Square window corners', description: 'Removes the rounded corners drawn around windows.', type: 'bool', default: false },
    { key: 'gtk3', name: 'Also apply to GTK3 apps', description: 'GTK3 is older but still used by many apps (GIMP, Inkscape, Zorin extras).', type: 'bool', default: true },
  ],

  apply(ctx) {
    const t = ctx.settings;
    const heights = { normal: [46, 34], compact: [36, 28], dense: [30, 24] };
    const [bar, btn] = heights[t.density] || heights.compact;

    const body = [
      `/* generated by Twiking — edit the density in the mod settings instead */`,
      `headerbar { min-height: ${bar}px; padding: 0 6px; }`,
      `headerbar button { min-height: ${btn - 6}px; min-width: ${btn - 6}px; padding: 2px 6px; }`,
      `button { padding-top: 3px; padding-bottom: 3px; }`,
      `menubutton > button { padding: 2px 6px; }`,
      `row { min-height: ${btn - 4}px; }`,
      t.squareCorners ? `window.csd, window.csd > decoration { border-radius: 0; box-shadow: none; }` : '',
      t.squareCorners ? `decoration { border-radius: 0; }` : '',
      '',
    ].filter(Boolean).join('\n');

    const gtk3Body = body.replace('window.csd, window.csd > decoration', 'decoration');

    const ops = [ctx.css(4, body)];
    if (t.gtk3) ops.push(ctx.css(3, gtk3Body));
    ctx.log(`GTK4 CSS updated (${t.density}${t.squareCorners ? ', square corners' : ''})`);
    return Promise.all(ops);
  },
};
