'use strict';
/* Pick the colour of every GTK window's titlebar through user CSS — the
 * Linux answer to Windhawk's "Auto Custom Titlebar Colors" (4.7★) and
 * "Windows 11 Custom Title Bar Colours" (4.58★).
 *
 * The rules go into a marked block in ~/.config/gtk-N.0/gtk.css, so Compact
 * GTK Layout, Rounded Window Corners and any hand-written CSS keep working
 * side by side. Qt and Electron apps draw their own titlebars. */

const PRESETS = [
  { value: 'graphite', label: 'Graphite', color: '#2f343a', text: '#ffffff' },
  { value: 'slate', label: 'Slate blue', color: '#3b4252', text: '#ffffff' },
  { value: 'blue', label: 'Zorin blue', color: '#1c71d8', text: '#ffffff' },
  { value: 'green', label: 'Green', color: '#26a269', text: '#ffffff' },
  { value: 'amber', label: 'Amber', color: '#b58900', text: '#1a1a1a' },
  { value: 'red', label: 'Red', color: '#c01c28', text: '#ffffff' },
  { value: 'purple', label: 'Purple', color: '#813d9c', text: '#ffffff' },
  { value: 'light', label: 'Light grey', color: '#ebebeb', text: '#1a1a1a' },
];

function preset(value) {
  return PRESETS.find((p) => p.value === value) || PRESETS[0];
}

module.exports = {
  meta: {
    id: 'titlebar-colour',
    name: 'Titlebar Colour',
    description: 'Paint the titlebar of every GTK window a chosen colour, in light or dark text — reversible byte-for-byte.',
    version: '1.0.0',
    author: 'Twiking',
    category: 'Appearance',
    icon: 'palette',
    license: 'MIT',
    tags: ['titlebar', 'colour', 'color', 'css', 'headerbar', 'gtk'],
    capabilities: ['files'],
    requires: { desktops: ['GNOME'] },
  },

  settings: [
    {
      key: 'preset',
      name: 'Titlebar colour',
      description: 'Applied to GTK apps — Files, Settings, Terminal and most Linux software. Qt and Electron apps keep their own look.',
      type: 'select',
      default: 'graphite',
      options: PRESETS.map((p) => ({ value: p.value, label: p.label })),
    },
    {
      key: 'text',
      name: 'Label text',
      description: '"Match colour" picks white or black to suit the preset; override it if an app uses its own text colour.',
      type: 'select',
      default: 'match',
      options: [
        { value: 'match', label: 'Match colour' },
        { value: '#ffffff', label: 'White' },
        { value: '#1a1a1a', label: 'Near black' },
      ],
    },
    {
      key: 'gtk3',
      name: 'Also apply to GTK3 apps',
      description: 'Older GTK3 apps (GIMP, Inkscape, many Zorin extras) style their titlebar with a different node.',
      type: 'bool',
      default: true,
    },
  ],

  apply(ctx) {
    const s = ctx.settings;
    const p = preset(s.preset);
    const color = p.color;
    const text = s.text === 'match' ? p.text : String(s.text);

    const gtk4 = [
      `/* generated by Twiking — change the colour in the mod settings */`,
      `headerbar { background: ${color}; color: ${text}; }`,
      `headerbar .title, headerbar .subtitle { color: ${text}; }`,
      `headerbar:backdrop { background: ${color}; color: ${text}; }`,
      '',
    ].join('\n');

    const ops = [ctx.css(4, gtk4)];
    if (s.gtk3) {
      ops.push(ctx.css(3, `titlebar, headerbar { background: ${color}; color: ${text}; }\n`));
    }
    ctx.log(`Titlebar colour: ${p.label} (${color})`);
    return Promise.all(ops);
  },
};
